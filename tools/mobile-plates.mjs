import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--use-angle=metal','--ignore-gpu-blocklist','--enable-gpu'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await page.goto('http://127.0.0.1:5177/', { waitUntil: 'networkidle' });
await page.waitForTimeout(5500);
await page.screenshot({ path: 'deliverables/source_board_files/m_lineart.png' });
await page.waitForFunction(() => !document.querySelector('.opening'), null, { timeout: 45000 });
await page.waitForTimeout(600);
await page.screenshot({ path: 'deliverables/source_board_files/m_hero.png' });
const max = await page.evaluate(() => document.documentElement.scrollHeight - window.innerHeight);
await page.evaluate((y) => window.scrollTo(0, y), Math.round(max * 0.2));
await page.waitForTimeout(1500);
await page.screenshot({ path: 'deliverables/source_board_files/m_detail.png' });
await page.evaluate((y) => window.scrollTo(0, y), Math.round(max * 0.97));
await page.waitForTimeout(1800);
await page.screenshot({ path: 'deliverables/source_board_files/m_explore.png' });
await browser.close();
console.log('mobile plates done');
